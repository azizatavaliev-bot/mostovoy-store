// Верхнеуровневые группы для сайдбар-фильтра витрины. Категория (свободный
// текст вроде «Умные часы», «Микрофоны») остаётся как есть — группа
// это более грубая корзина над ней, которую можно поправить вручную в админке.
const GROUPS = ["Гаджеты", "Игры", "Аксессуары", "Другое"];

// Готовые категории для подсказки в форме админки (datalist) — админ может
// ввести и своё, список не ограничивает, только ускоряет ввод и держит
// написание единообразным (важно для сайдбар-фильтра на витрине).
const CATEGORY_SUGGESTIONS = [
  "Смартфоны",
  "Ноутбуки",
  "MacBook",
  "Планшеты",
  "iPad",
  "Умные часы",
  "Apple Watch",
  "Наушники",
  "AirPods",
  "Умные колонки",
  "Фитнес-трекеры",
  "Смарт-очки",
  "Фены и стайлеры",
  "Фотоаппараты",
  "Игровые приставки",
  "Электронные книги",
  "Микрофоны",
  "Триммеры",
  "VR-гарнитуры",
];

// Порядок важен: первое совпадение побеждает.
const GROUP_RULES = [
  { group: "Игры", match: /приставк|playstation|xbox|nintendo|switch|steam\s*deck|игров/i },
  {
    group: "Аксессуары",
    match: /наушник|микрофон|часы|\bwatch\b|браслет|чехол|ремешок|зарядк|кабель|повербанк|airpods|фитнес.?трекер|смарт.?очк|\bglasses\b/i,
  },
  {
    group: "Гаджеты",
    match: /смартфон|телефон|ноутбук|macbook|планшет|\bipad\b|фен|триммер|электронн.{0,4}книг|фотоаппарат|камера|\bvr\b|гарнитур|колонк|speaker/i,
  },
];

// Подсказка группы по категории — только для удобства (значение по умолчанию
// в форме админки); окончательное решение всегда за человеком.
function guessGroup(category) {
  if (!category) return null;
  for (const rule of GROUP_RULES) if (rule.match.test(category)) return rule.group;
  return null;
}

module.exports = { GROUPS, CATEGORY_SUGGESTIONS, guessGroup };
