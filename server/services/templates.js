const KYRGYZ_MARKERS = /салам|баа|канча|кайда|дарек|жеткир|кепилдик|б[оө]л[уү]п\s+т[оө]л|алмаштыр|керекпи|барбы|иштейсиз|акча\s+жок|шаар/iu;

function pickText(entry, language) {
  const variants = entry[language] || entry.ru;
  return Array.isArray(variants) ? variants[Math.floor(Math.random() * variants.length)] : variants;
}

/** Готовый ответ по regex, иначе null — тогда решает ИИ-роутер или генерация. */
function classifyTemplate(text, { hasHistory = false } = {}) {
  const value = String(text || "").trim();
  if (!value) return null;
  const normalized = value.toLocaleLowerCase("ru-RU").replace(/ё/g, "е");
  const language = KYRGYZ_MARKERS.test(normalized) ? "ky" : "ru";
  const rule = RULES.find(
    (item) => (!item.requiresHistory || hasHistory) && item.pattern.test(normalized)
  );
  return rule ? { kind: rule.kind, text: pickText(TEMPLATES[rule.kind], language) } : null;
}

/** Текст шаблона по id из ИИ-роутера (null — id неизвестен). */
function templateById(id, language = "ru") {
  const entry = TEMPLATES[id];
  return entry ? pickText(entry, language) : null;
}

